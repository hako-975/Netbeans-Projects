    private void tabel() {
        DefaultTableModel t = new DefaultTableModel();
        t.addColumn("ID");
        t.addColumn("Nama");
        t.addColumn("Team");
        t.addColumn("Jenis Kelamin");
        t.addColumn("No HP");
        t.addColumn("Tanggal Lahir");
        jTable1.setModel(t);
        
        try {
            res = stat.executeQuery("select * from member");
            while (res.next()) {
                t.addRow(new Object[]{res.getString("id"),
                    res.getString("nama"),
                    res.getString("team"),
                    res.getString("jk"),
                    res.getString("no_hp"),
                    res.getString("tgl_lahir")
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, e);
        }
    }
    
